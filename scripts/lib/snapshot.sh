#!/usr/bin/env bash
#
# Pre-update restore point, sourced by scripts/update.sh (self-update sidecar) and scripts/install.sh (the
# `git pull && ./scripts/install.sh` upgrade path). hub-api runs `prisma migrate deploy` at boot and Prisma
# has no down-migrations, so BEFORE any image is swapped we take a logical dump of the hub database plus a copy
# of the .env (the secrets the dump's encrypted columns depend on). Mandatory: a failed snapshot aborts the
# update with nothing changed. The only opt-out is PRE_UPDATE_BACKUP=0 (env or .env) — unsafe, not advised.
#
# The caller provides: compose() (docker compose wrapper), log(), ENV_FILE and REPO_DIR; DRY=1 makes this print
# `RUN:` lines instead of touching anything (update.sh --dry-run) when TUGRA_SNAPSHOT_DRY=1. That is a DEDICATED
# variable, set only by update.sh from its own --dry-run flag — never an inherited generic DRY — so a real install
# can never silently skip the snapshot because of a stray environment variable.
#
# Output (all under ${TUGRA_BACKUP_DIR:-$REPO_DIR/backups}, dir 0700, files 0600; keeps the newest
# ${PRE_UPDATE_KEEP:-5} sets):
#   pre-update-<from>-to-<to>-<UTC stamp>.dump   pg_dump -Fc of the `tugra` database
#   pre-update-<from>-to-<to>-<UTC stamp>.env    copy of the .env (secret-bearing!)
# Restore: docs/disaster-recovery.md ("Restoring a pre-update snapshot").

# Config from the process env first, then the .env (so PRE_UPDATE_BACKUP=0 can live in either).
_snap_cfg() {
  local v="${!1:-}"
  if [ -z "$v" ] && [ -f "$ENV_FILE" ]; then v="$({ grep "^$1=" "$ENV_FILE" 2>/dev/null || true; } | head -n1 | cut -d= -f2-)"; fi
  printf '%s' "${v:-$2}"
}

# True when the operator explicitly disabled the snapshot.
snapshot_disabled() { [ "$(_snap_cfg PRE_UPDATE_BACKUP 1)" = "0" ]; }

SNAPSHOT_PATH=""   # set to the .dump path of the last successful (or dry-run) snapshot

# Delete all but the newest $1 sets (a set = .dump + its sibling .env). Best-effort.
_snap_prune() {
  local keep="$1" dir="$2" n=0 f
  case "$keep" in ''|*[!0-9]*) keep=5 ;; esac
  [ "$keep" -ge 1 ] || keep=1
  # shellcheck disable=SC2012  # names are generated by us (sanitized charset), mtime order is what we want
  for f in $(ls -1t "$dir"/pre-update-*.dump 2>/dev/null); do
    n=$((n + 1))
    if [ "$n" -gt "$keep" ]; then rm -f "$f" "${f%.dump}.env"; fi
  done
  return 0
}

_snap_run() {
  local from to dir stamp base out owner
  from="$(printf '%s' "$1" | tr -c 'A-Za-z0-9._-' '_')"
  to="$(printf '%s' "$2" | tr -c 'A-Za-z0-9._-' '_')"
  dir="$(_snap_cfg TUGRA_BACKUP_DIR "$REPO_DIR/backups")"
  stamp="$(date -u +%Y%m%dT%H%M%SZ)"
  base="$dir/pre-update-${from}-to-${to}-${stamp}"
  out="$base.dump"

  if [ "${TUGRA_SNAPSHOT_DRY:-0}" = "1" ]; then
    compose exec -T postgres pg_dump -U tugra -Fc tugra
    compose exec -T postgres pg_restore -l
    printf 'SNAPSHOT: %s\n' "$out"
    SNAPSHOT_PATH="$out"
    return 0
  fi

  # Owner of the .env (the installing admin). The updater sidecar runs as root; without handing the dir/files back
  # a non-root docker-group admin running install.sh later could not write into backups/. (macOS: stat -f.)
  owner="$(stat -c '%u:%g' "$ENV_FILE" 2>/dev/null || stat -f '%u:%g' "$ENV_FILE" 2>/dev/null || true)"
  mkdir -p "$dir" || { log "snapshot: cannot create $dir"; return 1; }
  if [ -n "$owner" ]; then chown "$owner" "$dir" 2>/dev/null || true; fi   # only effective as root
  if ! chmod 700 "$dir" 2>/dev/null && ! { [ -w "$dir" ] && [ -x "$dir" ]; }; then
    log "snapshot: cannot secure/write $dir (owned by another user, e.g. created by the root updater). Fix: sudo chown -R \"\$(id -un)\" \"$dir\" && chmod 700 \"$dir\""
    return 1
  fi
  if ! compose exec -T postgres pg_dump -U tugra -Fc tugra > "$out.part"; then
    log "snapshot: pg_dump failed (is the postgres container running?)"; rm -f "$out.part"; return 1
  fi
  # A custom-format dump starts with the magic "PGDMP"; pg_restore -l must also be able to read its TOC.
  if [ "$(head -c5 "$out.part" 2>/dev/null)" != "PGDMP" ]; then
    log "snapshot: the dump is empty or not a pg_dump custom archive"; rm -f "$out.part"; return 1
  fi
  if ! compose exec -T postgres pg_restore -l < "$out.part" >/dev/null; then
    log "snapshot: pg_restore could not read the dump back"; rm -f "$out.part"; return 1
  fi
  if [ -f "${TUGRA_SNAPSHOT_ENV_SRC:-$ENV_FILE}" ]; then
    if ! cp -p "${TUGRA_SNAPSHOT_ENV_SRC:-$ENV_FILE}" "$base.env.part"; then
      log "snapshot: could not copy the .env"; rm -f "$out.part" "$base.env.part"; return 1
    fi
    chmod 600 "$base.env.part"
    if [ -n "$owner" ]; then chown "$owner" "$base.env.part" 2>/dev/null || true; fi
    mv "$base.env.part" "$base.env" || { rm -f "$out.part" "$base.env.part"; return 1; }
  fi
  if [ -n "$owner" ]; then chown "$owner" "$out.part" 2>/dev/null || true; fi
  chmod 600 "$out.part" && mv "$out.part" "$out" || { rm -f "$out.part" "$base.env"; return 1; }
  SNAPSHOT_PATH="$out"
  _snap_prune "$(_snap_cfg PRE_UPDATE_KEEP 5)" "$dir"
  log "snapshot: pre-update backup saved to $out (+ .env copy)"
  return 0
}

# tugra_snapshot <from-version> <to-version>  ->  0 ok (SNAPSHOT_PATH set), 1 failed (nothing left behind).
tugra_snapshot() {
  local _um rc
  _um="$(umask)"; umask 077
  _snap_run "$@" && rc=0 || rc=$?   # never let `set -e` skip the umask restore below
  umask "$_um"
  return "$rc"
}
