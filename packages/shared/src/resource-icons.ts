/** Registries and namespaces that carry no meaning for the icon. */
const NAMESPACE_SKIP = new Set(["library", "bitnami", "bitnamilegacy", "linuxserver", "lscr.io"]);

function stripTag(ref: string): string {
  let s = ref.trim().toLowerCase();
  const at = s.indexOf("@");
  if (at >= 0) s = s.slice(0, at); // digest
  const slash = s.lastIndexOf("/");
  const colon = s.lastIndexOf(":");
  if (colon > slash) s = s.slice(0, colon); // tag (a colon before the last slash is a registry port)
  return s;
}

/**
 * The icon key for an image reference such as "docker.io/library/postgres:16-alpine" or "ghcr.io/x/n8n", or
 * null when nothing in the set fits. Matches the repository name first, then the full "owner/name" path; a bare
 * name that is itself a key ("n8n", "wordpress") matches directly.
 */
export function iconKeyForImage(image: string | null | undefined): string | null {
  if (!image || typeof image !== "string") return null;
  const segs = stripTag(image).split("/").filter(Boolean);
  // A first segment with a dot, a port or "localhost" is a registry host, not part of the name.
  if (segs.length > 1 && /[.:]|^localhost$/.test(segs[0])) segs.shift();
  const parts = segs.filter((p) => !NAMESPACE_SKIP.has(p));
  if (parts.length === 0) return null;
  const name = parts[parts.length - 1];
  const candidates = [parts.slice(-2).join("/"), name];
  for (const c of candidates) {
    const alias = IMAGE_ALIASES[c];
    if (alias) return KEY_SET.has(alias) ? alias : null;
  }
  if (KEY_SET.has(name)) return name;
  // postgres-16, postgresql-ha: the leading word names the engine.
  // Tooling around an engine (exporter, backup, proxy) is not the engine, so it gets no engine icon.
  const head = name.split(/[-_.]/)[0];
  if (head !== name && !/(exporter|backup|proxy|admin|operator|cli|sidecar)/.test(name)) {
    const a = IMAGE_ALIASES[head] ?? head;
    if (a && KEY_SET.has(a)) return a;
  }
  return null;
}

/** First hit over several image refs (a compose stack lists several), in order. */
export function iconKeyForImages(images: ReadonlyArray<string | null | undefined>): string | null {
  for (const i of images) {
    const k = iconKeyForImage(i);
    if (k) return k;
  }
  return null;
}
