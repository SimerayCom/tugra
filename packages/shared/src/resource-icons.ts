const KEY_SET: ReadonlySet<string> = new Set(RESOURCE_ICON_KEYS);

/** Longest key a client may send; the real keys are far shorter. */
export const RESOURCE_ICON_KEY_MAX = 64;

/** True when `key` names an icon in the vendored set. */
export function isResourceIconKey(key: unknown): key is string {
  return typeof key === "string" && key.length <= RESOURCE_ICON_KEY_MAX && KEY_SET.has(key);
}

