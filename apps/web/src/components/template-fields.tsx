"use client";

import { useState } from "react";
import type { FormField } from "../lib/types";
import { useT } from "../i18n/provider";
import { Field, Select, TextInput, fieldStyle } from "./form";

type TFn = (key: string, vars?: Record<string, string | number>) => string;

/**
 * Client-side mirror of the hub's validateInstallFields (apps/hub-api/.../template-manifest.ts): a
 * pre-submit UX gate. Iterates the field DEFINITIONS (so an untouched required field is caught),
 * returns a per-key error map. The server re-validates — this only gives fast feedback. `regex`/`min`/
 * `max` come from the manifest (author-controlled), not the user, so they are ReDoS-safe.
 */
export function validateFields(
  values: Record<string, string>,
  defs: FormField[] | undefined,
  t: TFn,
): Record<string, string> {
  const errors: Record<string, string> = {};
  for (const def of defs ?? []) {
    const value = values[def.key] ?? "";
    if (value === "") {
      if (def.required && !def.generate) errors[def.key] = t("templates.errRequired");
      continue; // blank + generate/optional → the server fills it
    }
    // Independent checks (mirror of the hub validateInstallFields sequential ifs — a `number` field
    // may ALSO carry a regex/options constraint); first failing check wins for this field.
    let err: string | undefined;
    if (def.type === "number" || def.type === "port") {
      const n = Number(value);
      if (!Number.isFinite(n)) err = t("templates.errNumber");
      else if (def.min != null && n < def.min) err = t("templates.errMin", { min: def.min });
      else if (def.max != null && n > def.max) err = t("templates.errMax", { max: def.max });
    }
    if (!err && def.type === "boolean" && value !== "true" && value !== "false") err = t("templates.errBool");
    if (!err && def.options && !def.options.some((o) => o.value === value)) err = t("templates.errOption");
    if (!err && def.regex && !new RegExp(def.regex).test(value)) err = t("templates.errFormat");
    if (err) errors[def.key] = err;
  }
  return errors;
}

/** A masked input with a text show/hide toggle (house convention — no shared widget). */
function PasswordInput({ id, value, onChange, placeholder }: { id?: string; value: string; onChange: (v: string) => void; placeholder?: string }) {
  const t = useT();
  const [show, setShow] = useState(false);
  return (
    <div style={{ display: "flex", gap: 6 }}>
      <TextInput id={id} type={show ? "text" : "password"} value={value} placeholder={placeholder} onChange={(e) => onChange(e.target.value)} style={{ flex: 1 }} />
      <button type="button" onClick={() => setShow((v) => !v)} style={{ ...fieldStyle, width: "auto", cursor: "pointer", color: "var(--c-tx3)", background: "var(--c-el)", border: "1px solid var(--c-bd)" }}>
        {show ? t("templates.hide") : t("templates.show")}
      </button>
    </div>
  );
}

/**
 * Renders a template's typed install fields (from the manifest) as controlled widgets. `random`/
 * `hidden` fields are omitted (the server auto-fills them). A generate-backed field left blank shows
 * an "Auto-generated" placeholder — its value is never pre-filled (no secret leaks). All values are
 * strings (booleans as "true"/"false"); the parent owns the `values` record.
 */
export function TemplateFields({
  fields,
  values,
  onChange,
  errors,
}: {
  fields: FormField[];
  values: Record<string, string>;
  onChange: (key: string, value: string) => void;
  errors: Record<string, string>;
}) {
  const t = useT();
  const visible = fields.filter((f) => f.type !== "hidden" && f.type !== "random");
  if (visible.length === 0) return null;
  return (
    <div style={{ display: "flex", flexDirection: "column", gap: 12 }}>
      {visible.map((f) => {
        const id = `tf-${f.key}`;
        const value = values[f.key] ?? "";
        const placeholder = f.generate && value === "" ? t("templates.autoGenerated") : undefined;
        return (
          <Field key={f.key} htmlFor={id} label={f.label + (f.required && !f.generate ? " *" : "")} hint={f.hint} error={errors[f.key]}>
            {f.type === "select" ? (
              <Select id={id} value={value} onChange={(v) => onChange(f.key, v)} options={f.options ?? []} />
            ) : f.type === "boolean" ? (
              // The Field label above already names this control (htmlFor → id); a bare checkbox
              // avoids repeating the label text next to it.
              <input id={id} type="checkbox" checked={value === "true"} onChange={(e) => onChange(f.key, e.target.checked ? "true" : "false")} style={{ width: 16, height: 16, accentColor: "var(--c-lapis)" }} />
            ) : f.type === "password" ? (
              <PasswordInput id={id} value={value} onChange={(v) => onChange(f.key, v)} placeholder={placeholder} />
            ) : (
              <TextInput
                id={id}
                type={f.type === "number" || f.type === "port" ? "number" : f.type === "email" ? "email" : "text"}
                value={value}
                placeholder={placeholder}
                min={f.min}
                max={f.max}
                onChange={(e) => onChange(f.key, e.target.value)}
              />
            )}
          </Field>
        );
      })}
    </div>
  );
}
